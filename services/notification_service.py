"""
Notification Service for Samvad PMO-CC.
Dispatches real-time alerts via Telegram Bot API or Twilio WhatsApp API
for critical site outages (>15 min) and customs delay risks.
Supports live API calls as well as simulation/audit logging.
"""
import os
import json
import logging
from typing import Dict, Any, Optional
import requests
from database.connection import execute_write

logger = logging.getLogger(__name__)

class NotificationDispatcher:
    def __init__(self, db_path: Optional[str] = None):
        self.db_path = db_path
        self.telegram_bot_token = os.getenv("TELEGRAM_BOT_TOKEN", "")
        self.telegram_chat_id = os.getenv("TELEGRAM_CHAT_ID", "")
        self.whatsapp_api_url = os.getenv("WHATSAPP_API_URL", "")
        self.whatsapp_token = os.getenv("WHATSAPP_TOKEN", "")

    def send_telegram_alert(self, message: str, chat_id: Optional[str] = None) -> Dict[str, Any]:
        """Dispatches an alert message to Telegram channel or field technician group."""
        target_chat = chat_id or self.telegram_chat_id
        if self.telegram_bot_token and target_chat:
            url = f"https://api.telegram.org/bot{self.telegram_bot_token}/sendMessage"
            payload = {
                "chat_id": target_chat,
                "text": message,
                "parse_mode": "HTML"
            }
            try:
                resp = requests.post(url, json=payload, timeout=8)
                status = "SUCCESS" if resp.status_code == 200 else f"FAILED: {resp.text}"
            except Exception as e:
                status = f"FAILED: {str(e)}"
        else:
            status = "SIMULATED"

        # Log into audit table
        execute_write(
            """
            INSERT INTO notification_audit_logs (channel, recipient, message_type, payload, sent_status)
            VALUES (?, ?, ?, ?, ?)
            """,
            ("Telegram", target_chat or "Samvad-NOC-Alerts", "EMERGENCY_ALERT", message, status),
            db_path=self.db_path
        )

        return {"channel": "Telegram", "status": status, "recipient": target_chat or "Samvad-NOC-Alerts"}

    def send_whatsapp_alert(self, message: str, phone_number: str = "+6281200001234") -> Dict[str, Any]:
        """Dispatches an alert message to WhatsApp recipient."""
        if self.whatsapp_api_url and self.whatsapp_token:
            headers = {
                "Authorization": f"Bearer {self.whatsapp_token}",
                "Content-Type": "application/json"
            }
            payload = {
                "to": phone_number,
                "type": "text",
                "text": {"body": message}
            }
            try:
                resp = requests.post(self.whatsapp_api_url, json=payload, headers=headers, timeout=8)
                status = "SUCCESS" if resp.status_code in (200, 201) else f"FAILED: {resp.text}"
            except Exception as e:
                status = f"FAILED: {str(e)}"
        else:
            status = "SIMULATED"

        # Log into audit table
        execute_write(
            """
            INSERT INTO notification_audit_logs (channel, recipient, message_type, payload, sent_status)
            VALUES (?, ?, ?, ?, ?)
            """,
            ("WhatsApp", phone_number, "OUTAGE_DISPATCH", message, status),
            db_path=self.db_path
        )

        return {"channel": "WhatsApp", "status": status, "recipient": phone_number}

    def dispatch_emergency_outage(self, site_id: str, site_name: str, duration_mins: int, root_cause: str) -> Dict[str, Any]:
        """Formats and triggers an emergency outage alert (>15 mins) to NOC & Field Technicians."""
        text = (
            f"🚨 <b>[SAMVAD PMO EMERGENCY OUTAGE ALERT]</b> 🚨\n\n"
            f"<b>Site ID:</b> {site_id}\n"
            f"<b>Site Name:</b> {site_name}\n"
            f"<b>Downtime Duration:</b> {duration_mins} minutes (Exceeded >15m SLA Buffer!)\n"
            f"<b>Initial Diagnostic:</b> {root_cause}\n"
            f"<b>Action Required:</b> Immediate dispatch of Level-2 Field Engineer to restore uptime to >=95.0% contract standard.\n\n"
            f"<i>Auto-generated by Samvad PMO Command Center Sentinel</i>"
        )
        tg_res = self.send_telegram_alert(text)
        wa_res = self.send_whatsapp_alert(text)
        return {"telegram": tg_res, "whatsapp": wa_res}

    def dispatch_customs_warning(self, bl_number: str, item_desc: str, eta: str, deadline: str, buffer_days: int) -> Dict[str, Any]:
        """Formats and triggers a customs seaport delay warning alert."""
        text = (
            f"⚠️ <b>[SAMVAD CUSTOMS DELAY WARNING]</b> ⚠️\n\n"
            f"<b>B/L Number:</b> {bl_number}\n"
            f"<b>Item:</b> {item_desc}\n"
            f"<b>ETA Port:</b> {eta}\n"
            f"<b>Commissioning Deadline:</b> {deadline}\n"
            f"<b>Remaining Buffer:</b> {buffer_days} Days (CRITICAL RED BUFFER!)\n"
            f"<b>Action:</b> Expedite customs clearance with forwarding agent to prevent SLA penalty."
        )
        return self.send_telegram_alert(text)
